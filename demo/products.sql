-- Synthetic demonstration catalogue; not a bank offer.
-- Runs only on first initialization of the Compose products volume.
CREATE TABLE IF NOT EXISTS products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(100) NOT NULL UNIQUE,
    purposes TEXT NOT NULL,
    interest DOUBLE PRECISION NOT NULL,
    discount_interest DOUBLE PRECISION NOT NULL,
    discount_conditions TEXT,
    min_sum INTEGER NOT NULL,
    max_sum INTEGER NOT NULL,
    min_duration INTEGER NOT NULL,
    max_duration INTEGER NOT NULL,
    main_difference TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS product_repayment_types (
    product_id BIGINT NOT NULL REFERENCES products(id),
    repayment_type VARCHAR(255) NOT NULL,
    PRIMARY KEY (product_id, repayment_type)
);
